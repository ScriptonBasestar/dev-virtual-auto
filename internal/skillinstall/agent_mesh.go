package skillinstall

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	pathpkg "path"
	"sort"
	"strings"

	bundled "github.com/ScriptonBasestar/dva/skills"
)

// agentMeshBundle compiles the portable Agent Skills bundle to Agent Mesh's
// flat Markdown format. References are inlined because Agent Mesh's handling
// of a sibling reference bundle is not part of this install contract.
func agentMeshBundle() (skillBundle, error) {
	bundle := skillBundle{contents: make(map[string][]byte, len(bundled.Names))}
	for _, name := range bundled.Names {
		contents, err := renderAgentMeshSkill(name)
		if err != nil {
			return skillBundle{}, err
		}
		path := name + ".md"
		digest := sha256.Sum256(contents)
		bundle.files = append(bundle.files, fileHash{Path: path, SHA: hex.EncodeToString(digest[:])})
		bundle.contents[path] = contents
	}
	sort.Slice(bundle.files, func(i, j int) bool { return bundle.files[i].Path < bundle.files[j].Path })
	return bundle, nil
}

func renderAgentMeshSkill(name string) ([]byte, error) {
	skillPath := pathpkg.Join(name, "SKILL.md")
	skill, err := bundled.Files.ReadFile(skillPath)
	if err != nil {
		return nil, err
	}
	body, err := stripFrontmatter(string(skill))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", skillPath, err)
	}
	body = rewriteLocalSkillPaths(name, body)
	var output strings.Builder
	output.WriteString("<!-- Generated by `dva skill install --runtime agent-mesh`; do not edit.\n")
	output.WriteString("Source version and bundle SHA-256 are recorded by `dva skill status`.\n")
	output.WriteString("Canonical source: https://github.com/ScriptonBasestar/dva/tree/master/skills/")
	output.WriteString(name)
	output.WriteString(". Relative reference documents are inlined below because Agent Mesh reference-bundle resolution is not assumed. -->\n\n")
	output.WriteString(strings.TrimSpace(body))

	for _, source := range []struct {
		kind, directory string
	}{
		{kind: "Reference", directory: "references"},
		{kind: "Asset", directory: "assets"},
	} {
		paths, err := bundledTextPaths(name, source.directory)
		if err != nil {
			return nil, err
		}
		for _, relative := range paths {
			contents, err := bundled.Files.ReadFile(pathpkg.Join(name, relative))
			if err != nil {
				return nil, err
			}
			output.WriteString("\n\n<a id=\"")
			output.WriteString(inlineAnchor(name, relative))
			output.WriteString("\"></a>\n\n## ")
			output.WriteString(source.kind)
			output.WriteString(": ")
			output.WriteString(relative)
			output.WriteString("\n\n")
			if source.kind == "Asset" {
				output.WriteString("```")
				output.WriteString(assetLanguage(relative))
				output.WriteString("\n")
				output.WriteString(strings.TrimSpace(string(contents)))
				output.WriteString("\n```")
			} else {
				output.WriteString(strings.TrimSpace(demoteHeadings(rewriteLocalSkillPaths(name, string(contents)), 2)))
			}
		}
	}
	return []byte(output.String() + "\n"), nil
}

func stripFrontmatter(source string) (string, error) {
	if !strings.HasPrefix(source, "---\n") {
		return source, nil
	}
	end := strings.Index(source[len("---\n"):], "\n---\n")
	if end < 0 {
		return "", fmt.Errorf("unterminated YAML frontmatter")
	}
	return source[len("---\n")+end+len("\n---\n"):], nil
}

func bundledTextPaths(skill, directory string) ([]string, error) {
	var paths []string
	err := fs.WalkDir(bundled.Files, pathpkg.Join(skill, directory), func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if !entry.IsDir() {
			paths = append(paths, strings.TrimPrefix(path, skill+"/"))
		}
		return nil
	})
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	sort.Strings(paths)
	return paths, err
}

func rewriteLocalSkillPaths(skill, source string) string {
	for _, directory := range []string{"references", "assets"} {
		paths, err := bundledTextPaths(skill, directory)
		if err != nil {
			continue
		}
		for _, relative := range paths {
			anchor := "#" + inlineAnchor(skill, relative)
			canonical := "https://github.com/ScriptonBasestar/dva/blob/master/skills/" + skill + "/" + relative
			source = strings.ReplaceAll(source, "]("+relative+")", "]("+anchor+")")
			source = strings.ReplaceAll(source, "]("+relative+"#", "]("+canonical+"#")
			source = strings.ReplaceAll(source, relative, "[inline "+relative+"]("+anchor+")")
		}
	}
	return source
}

func inlineAnchor(skill, relative string) string {
	replacer := strings.NewReplacer("/", "-", ".", "-", "_", "-")
	return "dva-" + replacer.Replace(skill+"-"+relative)
}

func demoteHeadings(source string, levels int) string {
	var output strings.Builder
	for _, line := range strings.Split(source, "\n") {
		if strings.HasPrefix(line, "#") {
			count := len(line) - len(strings.TrimLeft(line, "#"))
			if count > 0 && count < 7 && len(line) > count && line[count] == ' ' {
				line = strings.Repeat("#", levels) + line
			}
		}
		output.WriteString(line)
		output.WriteByte('\n')
	}
	return strings.TrimSuffix(output.String(), "\n")
}

func assetLanguage(path string) string {
	if strings.HasSuffix(path, ".yml") || strings.HasSuffix(path, ".yaml") {
		return "yaml"
	}
	return "text"
}
