// Command agentdenygen renders internal/agentdeny.GatedCommands into
// docs/agent-deny-rules.md. It is the single converter behind `make generate` for this
// document; edit internal/agentdeny/rules.go (the canonical list) or this file's static
// prose sections, never docs/agent-deny-rules.md directly — `make check-generate` fails
// if the rendered doc has drifted from either source.
//
// This is TASK-286's binding for completion criterion 1 ("a new gated command cannot
// ship without a rule"): adding an entry to GatedCommands and forgetting to regenerate
// this doc fails CI. It is not yet a binding against the live cobra command tree —
// TASK-282 has not landed 'config env seal'/'config env show' in this checkout as of
// this card, so there is no command tree to check against. See this doc's own "Binding
// this list to the CLI" section for the follow-up this leaves recorded.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ScriptonBasestar/dva/internal/agentdeny"
)

func main() {
	root := flag.String("root", ".", "repo root")
	flag.Parse()

	out := filepath.Join(*root, "docs", "agent-deny-rules.md")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "agentdenygen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(out, []byte(render()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "agentdenygen:", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", out)
}

func render() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n## Gated commands\n\n")
	b.WriteString("| ID | Command | Deny patterns | Reason | Source |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, command := range agentdeny.GatedCommands {
		patterns := make([]string, len(command.Patterns()))
		for i, p := range command.Patterns() {
			patterns[i] = "`" + p + "`"
		}
		b.WriteString(fmt.Sprintf("| `%s` | `%s` | %s | %s | %s |\n",
			command.ID, command.Argv, strings.Join(patterns, "<br>"), command.Reason, command.Source))
	}
	b.WriteString(coverageTable)
	b.WriteString(honestLimits)
	b.WriteString(binding)
	return b.String()
}

