const binding = `
## Binding this list to the CLI

` + "`make check-generate`" + ` fails if this document has drifted from
` + "`internal/agentdeny.GatedCommands`" + ` — the source list above — so a change to that list
that is not accompanied by regenerating this doc is caught in CI.

That is not yet a binding against DVA's *live* cobra command tree: TASK-282 has not
landed the ` + "`seal`" + `/` + "`show`" + ` subcommands into this checkout (only ` + "`unseal`" + ` and
` + "`edit`" + ` exist today), so there is no command tree to cross-check yet. This list was
written from the frozen argv contract in
` + "`tasks/done/281-freeze-gated-env-bridge-commands.md`" + ` §3-5/§3-7 instead. A live-tree
binding — a test walking the registered cobra tree and asserting every
` + "`env_bridge`" + `-shaped command has a ` + "`GatedCommands`" + ` entry — is a named follow-up once
TASK-282 lands, not assumed to already exist.

## What "never clobbers" means here

Installing merges the desired deny patterns into the target file's
` + "`permissions.deny`" + ` array by parsing it, adding only the entries that are missing, and
re-serializing. Every other key's *value* — including sibling ` + "`permissions.allow`" + `/
` + "`permissions.ask`" + ` arrays, any pre-existing user-added deny entries, and every unrelated
top-level key — survives byte-for-byte in content, proven by
` + "`internal/agentdeny/deploy_test.go`" + `'s ` + "`TestInstallDoesNotClobberSiblingContent`" + `. What
is not preserved is the file's exact formatting (indentation, key order) of the
containers this package touches — re-serializing a Go map does not reproduce arbitrary
source whitespace or key ordering. This is a deliberate, recorded trade-off: byte-level
source-position surgery was judged disproportionate to the risk it would close, given
that no *content* is ever lost or reinterpreted.

## Ownership model

` + "`dva agent-deny install/status/uninstall`" + ` reuses ` + "`internal/skillinstall.Scope`" + `
directly (` + "`--scope user or project`" + `) and a skillinstall-style receipt
(` + "`internal/agentdeny/receipt.go`" + `, same atomic temp-file+fsync+rename write discipline
as ` + "`internal/skillinstall`" + `'s own receipts) to track exactly which pattern strings DVA
added at a destination, so status can detect a locally removed/edited DVA-owned pattern
and uninstall can remove only entries that are still present verbatim — refusing the
whole operation on any drift rather than guessing which are still safe to remove.

This package does **not** reuse skillinstall's takeover/backup machinery: that solves a
different problem (a skill install owns a whole destination directory and can collide
with a foreign, non-DVA-created one of the same name). A deny-rule install only ever
merges known strings into one JSON array in a file the user may already own — it never
replaces or deletes content it doesn't recognize, so there is no foreign collision for a
takeover to resolve.

## init integration boundary

` + "`dva init`" + ` does not write this or any other agent settings file as part of this card.
` + "`internal/cli/init.go`" + `, ` + "`internal/cli/init_scaffold.go`" + `, and their tests have zero
references to ` + "`skillinstall`" + ` or a settings file (confirmed by grep) — deploying deny
rules stays an explicit, separate ` + "`dva agent-deny install`" + ` invocation. Whether/how
` + "`init`" + ` should *recommend* running it is TASK-249's boundary, not this card's.
`
